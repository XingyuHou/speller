import { describe, expect, it } from 'vitest'
import { SPELL_CONFIG } from '../src/config'
import { SpellBar } from '../src/spell/SpellBar'

describe('SpellBar', () => {
  it('loads a whole word with identifiable source letters and ignores renewed contact', () => {
    const bar = new SpellBar()
    expect(bar.loadWord('blue', 'PALM')).toBe(true)
    expect(bar.sourceId).toBe('blue')
    expect(new Set(bar.letters.map(l => l.id)).size).toBe(4)
    expect(bar.letters.every(l => l.origin === 'word')).toBe(true)
    const before = bar.letters
    bar.insert(2, 0)
    expect(bar.word).toBe('LPAM')
    expect(before.map(l => l.char).join('')).toBe('PALM')
    expect(bar.loadWord('blue', 'PALM')).toBe(false)
    expect(bar.word).toBe('LPAM')
    expect(bar.canUndo).toBe(true)
  })

  it('appends individual pickups once and does not lose duplicate characters from separate places', () => {
    const bar = new SpellBar()
    expect(bar.collect('a', 'L')).toBe(true)
    expect(bar.collect('a', 'L')).toBe(false)
    expect(bar.collect('b', 'L')).toBe(true)
    expect(bar.letters.map(l => l.id)).toEqual(['a', 'b'])
    expect(bar.letters.every(l => l.origin === 'collected')).toBe(true)
    expect(bar.collected('b')).toBe(true)
    expect(bar.sourceId).toBeNull()
  })

  it('rejects invalid, empty, and oversized loads without overwriting the current bar', () => {
    const bar = new SpellBar()
    bar.collect('first', 'I')
    for (const word of ['', 'A1', 'X'.repeat(SPELL_CONFIG.capacity + 1)]) {
      expect(bar.loadWord('bad', word)).toBe(false)
    }
    expect(bar.collect('many', 'AB')).toBe(false)
    expect(bar.collect('space', ' ')).toBe(false)
    expect(bar.word).toBe('I')
    for (let i = 1; i < SPELL_CONFIG.capacity; i++) expect(bar.collect(String(i), 'X')).toBe(true)
    expect(bar.collect('extra', 'Y')).toBe(false)
    expect(bar.collected('extra')).toBe(false)
    expect(bar.letters).toHaveLength(SPELL_CONFIG.capacity)
  })

  it('distinguishes insertion from swap and unwinds both in reverse order', () => {
    const bar = new SpellBar()
    bar.loadWord('blue', 'PALM')
    expect(bar.insert(0, 3)).toBe(true)
    expect(bar.word).toBe('ALMP')
    expect(bar.swap(0, 1)).toBe(true)
    expect(bar.word).toBe('LAMP')
    expect(bar.undo()).toBe(true)
    expect(bar.word).toBe('ALMP')
    expect(bar.undo()).toBe(true)
    expect(bar.word).toBe('PALM')
    expect(bar.undo()).toBe(false)
  })

  it('ignores same-slot and out-of-bounds operations without creating history', () => {
    const bar = new SpellBar()
    bar.loadWord('blue', 'PALM')
    expect(bar.insert(1, 1)).toBe(false)
    expect(bar.insert(-1, 0)).toBe(false)
    expect(bar.swap(0, 4)).toBe(false)
    expect(bar.swap(1.5, 2)).toBe(false)
    expect(bar.swap(2, 2)).toBe(false)
    expect(bar.canUndo).toBe(false)
  })

  it('keeps new pickups when undoing a move made before they were collected', () => {
    const bar = new SpellBar()
    bar.collect('l', 'L')
    bar.collect('i', 'I')
    bar.swap(0, 1)
    bar.collect('s', 'S')
    bar.swap(0, 2)
    bar.undo()
    expect(bar.word).toBe('ILS')
    bar.undo()
    expect(bar.word).toBe('LIS')
    expect(bar.collect('s', 'S')).toBe(false)
  })

  it('removes the selected pickup by identity, defaults to the last, and undoes in edit order', () => {
    const bar = new SpellBar()
    bar.collect('first-l', 'L')
    bar.collect('i', 'I')
    bar.collect('other-l', 'L')
    bar.swap(1, 2)
    expect(bar.deleteLetter(0)).toBe(true)
    expect(bar.collected('first-l')).toBe(false)
    expect(bar.collected('other-l')).toBe(true)
    expect(bar.deleteLetter()).toBe(true)
    expect(bar.letters.map(l => l.id)).toEqual(['other-l'])
    bar.undo()
    bar.undo()
    expect(bar.letters.map(l => l.id)).toEqual(['first-l', 'other-l', 'i'])
    expect(bar.collect('first-l', 'L')).toBe(false)
    bar.undo()
    expect(bar.word).toBe('LIL')
  })

  it('uses one map ID when a deleted letter was collected again before undo', () => {
    const bar = new SpellBar()
    bar.collect('l', 'L')
    bar.collect('i', 'I')
    bar.deleteLetter(0)
    bar.collect('t', 'T')
    expect(bar.collect('l', 'L')).toBe(true)
    expect(bar.word).toBe('ITL')
    bar.undo()
    expect(bar.word).toBe('LIT')
    expect(bar.collect('l', 'L')).toBe(false)
    expect(bar.canUndo).toBe(false)
  })

  it('leaves blue words and stashed deletion history alone, including empty and invalid selections', () => {
    const bar = new SpellBar()
    expect(bar.deleteLetter()).toBe(false)
    bar.collect('l', 'L')
    expect(bar.deleteLetter(-1)).toBe(false)
    expect(bar.deleteLetter(1)).toBe(false)
    expect(bar.deleteLetter(0.5)).toBe(false)
    expect(bar.canUndo).toBe(false)
    bar.deleteLetter()
    bar.loadWord('words', 'WORDS')
    expect(bar.deleteLetter()).toBe(false)
    expect(bar.deleteLetter(1)).toBe(false)
    expect(bar.canUndo).toBe(false)
    expect(bar.word).toBe('WORDS')
    bar.collect('i', 'I')
    bar.consumeWord()
    expect(bar.word).toBe('I')
    bar.undo()
    expect(bar.word).toBe('LI')
  })

  it('restores a deleted glyph from a full row without exceeding capacity', () => {
    const bar = new SpellBar()
    for (let i = 0; i < SPELL_CONFIG.capacity; i++) bar.collect(String(i), 'L')
    bar.deleteLetter(0)
    bar.collect('new', 'N')
    bar.undo()
    expect(bar.collected('0')).toBe(true)
    expect(bar.collected('new')).toBe(false)
    expect(bar.letters).toHaveLength(SPELL_CONFIG.capacity)
  })

  it('restores the stashed collection, order, and own undo history after a blue spell', () => {
    const bar = new SpellBar()
    bar.collect('l', 'L')
    bar.collect('i', 'I')
    bar.swap(0, 1)
    bar.loadWord('palm-A', 'PALM')
    bar.swap(0, 3)
    bar.collect('s', 'S')
    expect(bar.word).toBe('MALP')
    bar.consumeWord()
    expect(bar.word).toBe('ILS')
    expect(bar.spentWord('palm-A')).toBe(true)
    expect(bar.loadWord('palm-A', 'PALM')).toBe(false)
    bar.undo()
    expect(bar.word).toBe('LIS')
    expect(bar.loadWord('palm-B', 'PALM')).toBe(true)
  })

  it('starts a new run with pickup and source identities available again', () => {
    const bar = new SpellBar()
    bar.collect('l', 'L')
    bar.loadWord('palm', 'PALM')
    bar.consumeWord()
    bar.reset()
    expect(bar.word).toBe('')
    expect(bar.canUndo).toBe(false)
    expect(bar.collect('l', 'L')).toBe(true)
    expect(bar.loadWord('palm', 'PALM')).toBe(true)
  })
})

it('can put away an unused blue word and load it again on a later visit', () => {
  const bar = new SpellBar()
  bar.loadWord('palm', 'PALM')
  bar.collect('hello:2', 'L')
  bar.releaseWord()
  expect(bar.word).toBe('L')
  expect(bar.loadWord('palm', 'PALM')).toBe(true)
  bar.consumeWord()
  expect(bar.word).toBe('L')
})
