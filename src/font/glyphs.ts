export interface Point {
  x: number
  y: number
}

export interface Glyph {
  advance: number
  strokes: Point[][]
}

// Original pen paths on a ten-unit cap-height grid, with one pen lift per string.
// Store normalized coordinates so lettering, dots, and joins all scale together.
function glyph(width: number, ...paths: string[]): Glyph {
  return {
    advance: width / 10,
    strokes: paths.map(path => path.split(' ').map(pair => {
      const [x, y] = pair.split(',').map(Number)
      return { x: x / 10, y: y / 10 }
    })),
  }
}

